import mongoose, { Schema, Document } from 'mongoose';

export interface IAlert extends Document {
  type: 'water_quality' | 'flood' | 'unsafe_zone' | 'waste' | 'maintenance' | 'system';
  severity: 'info' | 'warning' | 'danger' | 'critical';
  title: string;
  message: string;
  location?: {
    type: 'Point';
    coordinates: [number, number];
  };
  affectedRadius?: number;
  relatedEntity?: {
    entityType: 'sensor' | 'unsafe_zone' | 'waste_hotspot' | 'report';
    entityId: mongoose.Types.ObjectId;
  };
  parameters?: {
    parameter: string;
    value: number;
    threshold: number;
    unit: string;
  }[];
  recommendations: string[];
  expiresAt?: Date;
  status: 'active' | 'resolved' | 'expired';
  resolvedAt?: Date;
  resolvedBy?: mongoose.Types.ObjectId;
  recipientType: 'all' | 'nearby' | 'specific';
  recipients?: mongoose.Types.ObjectId[];
  notificationsSent: number;
  metadata?: {
    autoGenerated?: boolean;
    triggeredBy?: string;
  };
  createdAt: Date;
  updatedAt: Date;
}

const alertSchema = new Schema<IAlert>(
  {
    type: {
      type: String,
      enum: ['water_quality', 'flood', 'unsafe_zone', 'waste', 'maintenance', 'system'],
      required: true,
    },
    severity: {
      type: String,
      enum: ['info', 'warning', 'danger', 'critical'],
      required: true,
    },
    title: {
      type: String,
      required: true,
      trim: true,
      maxlength: 200,
    },
    message: {
      type: String,
      required: true,
      maxlength: 1000,
    },
    location: {
      type: {
        type: String,
        enum: ['Point'],
      },
      coordinates: {
        type: [Number],
      },
    },
    affectedRadius: {
      type: Number,
      min: 0,
    },
    relatedEntity: {
      entityType: {
        type: String,
        enum: ['sensor', 'unsafe_zone', 'waste_hotspot', 'report'],
      },
      entityId: Schema.Types.ObjectId,
    },
    parameters: [
      {
        parameter: String,
        value: Number,
        threshold: Number,
        unit: String,
      },
    ],
    recommendations: [String],
    expiresAt: Date,
    status: {
      type: String,
      enum: ['active', 'resolved', 'expired'],
      default: 'active',
    },
    resolvedAt: Date,
    resolvedBy: {
      type: Schema.Types.ObjectId,
      ref: 'User',
    },
    recipientType: {
      type: String,
      enum: ['all', 'nearby', 'specific'],
      default: 'all',
    },
    recipients: [
      {
        type: Schema.Types.ObjectId,
        ref: 'User',
      },
    ],
    notificationsSent: {
      type: Number,
      default: 0,
      min: 0,
    },
    metadata: {
      autoGenerated: { type: Boolean, default: false },
      triggeredBy: String,
    },
  },
  {
    timestamps: true,
  }
);

// Indexes
alertSchema.index({ location: '2dsphere' });
alertSchema.index({ status: 1, severity: 1 });
alertSchema.index({ type: 1, createdAt: -1 });
alertSchema.index({ expiresAt: 1 });

export const Alert = mongoose.model<IAlert>('Alert', alertSchema);
